// ============================================================
// SENSOR DETAIL PAGE
// ============================================================

export default function SensorDetailPage({
  sensor,
  reading,
  history,
  now
}) {

  const status = sensorStatus(reading, now);

  const typeLabels = labels[sensor.type] || {};

  const config = graphConfig[sensor.type];


  // ==========================================================
  // GRAPH DATA
  // ==========================================================

  const series = config
    ? config.map(line => ({
        ...line,

        points: history.map(item => {

          const value = Number(item.data?.[line.key]);

          return Number.isFinite(value)
            ? value
            : NaN;
        })
      }))
    : [];


  // ==========================================================
  // UI
  // ==========================================================

  return (
    <section className="detail-view">

      {/* ======================================================
          SENSOR LOCATION / TYPE
          ====================================================== */}

      <p className="eyebrow">

        {sensor.location.replaceAll("-", " ")}

        {" · "}

        {sensor.type}

      </p>


      {/* ======================================================
          SENSOR TITLE / STATUS
          ====================================================== */}

      <div className="detail-title-row">

        <h1>{sensor.id}</h1>

        <span className="detail-status">

          <StatusLED color={status} />

          {statusText(status)}

        </span>

      </div>


      {/* ======================================================
          CONNECTION INFORMATION
          ====================================================== */}

      <p className="detail-subline">

        {sensor.ip}:{sensor.port}

        {" · "}

        <span className="topic">
          {sensor.topic}
        </span>

        {" · "}

        {reading
          ? `Last received: ${new Date(
              reading.receivedAt
            ).toLocaleTimeString()}`
          : "No reading received yet"
        }

      </p>


      {/* ======================================================
          FCAD IDENTIFICATION
          ====================================================== */}

      {sensor.type === "fcad" && reading && (

        <div className="reading-grid">

          <ReadingCard
            label="Unit name"
            value={formatValue(
              "sensorName",
              reading.data?.sensorName
            )}
            hasReading={!!reading}
          />

          <ReadingCard
            label="MAC ID"
            value={formatValue(
              "macId",
              reading.data?.macId
            )}
            hasReading={!!reading}
          />

        </div>

      )}


      {/* ======================================================
          READING BOXES
          ====================================================== */}

      <div className="reading-grid">

        {Object.entries(typeLabels)

          // sensorName and macId are already displayed
          // separately for FCAD.
          .filter(([key]) => {

            if (
              sensor.type === "fcad" &&
              (
                key === "sensorName" ||
                key === "macId"
              )
            ) {
              return false;
            }

            return true;
          })

          .map(([key, text]) => {

            const value = reading
              ? formatValue(
                  key,
                  reading.data?.[key]
                )
              : "—";

            return (
              <ReadingCard
                key={key}
                label={text}
                value={value}
                hasReading={!!reading}
              />
            );
          })}

      </div>


      {/* ======================================================
          NO DATA MESSAGE
          ====================================================== */}

      {!reading && (

        <p className="empty-copy">

          Waiting for data from this sensor.
          The boxes above will fill in automatically.

        </p>

      )}


      {/* ======================================================
          LIVE GRAPH
          ====================================================== */}

      {config && (

        <>

          <h2>Live graph</h2>

          <SensorGraph
            series={series}
            yLabel={
              config.length === 1
                ? config[0].label
                : "Value"
            }
          />

        </>

      )}

    </section>
  );
}