// ============================================================
// FORMAT FCAD VALUE
// ============================================================

function formatValue(key, value) {

  if (value === undefined || value === null || value === "") {
    return "—";
  }

  // Boolean / strings don't need numeric formatting.
  if (typeof value === "string") {
    return value;
  }

  if (typeof value === "number") {

    // Values already decoded to 2 decimal places.
    if (
      [
        "koRipG",
        "koRipH",
        "ripAmpG",
        "ripAmpH",
        "hvFeedbackG",
        "hvFeedbackH",
        "flowInOuterLoop",
        "ko1G",
        "ko3H"
      ].includes(key)
    ) {
      return `${value.toFixed(2)}${valueUnits[key] || ""}`;
    }

    return `${value}${valueUnits[key] || ""}`;
  }

  return String(value);
}


